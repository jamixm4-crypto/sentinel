use sha2::{Digest, Sha256};
use std::fs::File;
use std::io::{Read, Write};
use std::path::Path;

const MAGIC_HEADER: &[u8; 8] = b"SENTINEL";

pub fn encrypt_report_file(input_path: &Path, output_path: &Path, password: &str) -> std::io::Result<()> {
    let mut input_file = File::open(input_path)?;
    let mut plaintext = Vec::new();
    input_file.read_to_end(&mut plaintext)?;

    // Generate pseudo-random salt based on time and input length
    let salt = format!("{:x}", chrono::Utc::now().timestamp_nanos_opt().unwrap_or(0));
    let salt_bytes = salt.as_bytes();

    // Derive keystream using iterated SHA-256 (PBKDF-like)
    let mut key = Sha256::digest(format!("{}{}", password, salt).as_bytes());
    for _ in 0..10_000 {
        key = Sha256::digest(&key);
    }

    let mut ciphertext = Vec::with_capacity(plaintext.len());
    let mut block_counter: u64 = 0;
    for chunk in plaintext.chunks(32) {
        let mut hasher = Sha256::new();
        hasher.update(&key);
        hasher.update(block_counter.to_le_bytes());
        let stream_block = hasher.finalize();

        for (i, &byte) in chunk.iter().enumerate() {
            ciphertext.push(byte ^ stream_block[i]);
        }
        block_counter += 1;
    }

    let mut output_file = File::create(output_path)?;
    output_file.write_all(MAGIC_HEADER)?;
    let salt_len = salt_bytes.len() as u32;
    output_file.write_all(&salt_len.to_le_bytes())?;
    output_file.write_all(salt_bytes)?;
    output_file.write_all(&ciphertext)?;

    Ok(())
}

pub fn decrypt_report_file(input_path: &Path, output_path: &Path, password: &str) -> Result<(), String> {
    let mut file = File::open(input_path).map_err(|e| e.to_string())?;
    let mut header = [0u8; 8];
    file.read_exact(&mut header).map_err(|e| e.to_string())?;

    if &header != MAGIC_HEADER {
        return Err("Invalid Sentinel encrypted file format (magic header mismatch)".to_string());
    }

    let mut salt_len_bytes = [0u8; 4];
    file.read_exact(&mut salt_len_bytes).map_err(|e| e.to_string())?;
    let salt_len = u32::from_le_bytes(salt_len_bytes) as usize;

    let mut salt_bytes = vec![0u8; salt_len];
    file.read_exact(&mut salt_bytes).map_err(|e| e.to_string())?;
    let salt = String::from_utf8_lossy(&salt_bytes);

    let mut ciphertext = Vec::new();
    file.read_to_end(&mut ciphertext).map_err(|e| e.to_string())?;

    let mut key = Sha256::digest(format!("{}{}", password, salt).as_bytes());
    for _ in 0..10_000 {
        key = Sha256::digest(&key);
    }

    let mut plaintext = Vec::with_capacity(ciphertext.len());
    let mut block_counter: u64 = 0;
    for chunk in ciphertext.chunks(32) {
        let mut hasher = Sha256::new();
        hasher.update(&key);
        hasher.update(block_counter.to_le_bytes());
        let stream_block = hasher.finalize();

        for (i, &byte) in chunk.iter().enumerate() {
            plaintext.push(byte ^ stream_block[i]);
        }
        block_counter += 1;
    }

    let mut out_file = File::create(output_path).map_err(|e| e.to_string())?;
    out_file.write_all(&plaintext).map_err(|e| e.to_string())?;

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_report_encryption_and_decryption_roundtrip() {
        let temp_dir = std::env::temp_dir();
        let orig_file = temp_dir.join("test_sentinel_report.txt");
        let enc_file = temp_dir.join("test_sentinel_report.enc");
        let dec_file = temp_dir.join("test_sentinel_report_dec.txt");

        let test_content = "This is a confidential forensic security report generated by Sentinel.";
        std::fs::write(&orig_file, test_content).unwrap();

        let password = "MyVeryStrongPassword!2026";

        encrypt_report_file(&orig_file, &enc_file, password).unwrap();
        assert!(enc_file.exists());

        // Ensure encrypted content is different from plaintext
        let enc_bytes = std::fs::read(&enc_file).unwrap();
        assert_ne!(enc_bytes, test_content.as_bytes());

        // Decrypt with correct password
        decrypt_report_file(&enc_file, &dec_file, password).unwrap();
        let restored = std::fs::read_to_string(&dec_file).unwrap();
        assert_eq!(restored, test_content);

        // Decrypt with wrong password yields corrupted plaintext (or error)
        let dec_wrong = temp_dir.join("test_wrong.txt");
        decrypt_report_file(&enc_file, &dec_wrong, "WrongPass").unwrap();
        let wrong_content = std::fs::read_to_string(&dec_wrong).unwrap_or_default();
        assert_ne!(wrong_content, test_content);

        // Clean up
        let _ = std::fs::remove_file(orig_file);
        let _ = std::fs::remove_file(enc_file);
        let _ = std::fs::remove_file(dec_file);
        let _ = std::fs::remove_file(dec_wrong);
    }
}

